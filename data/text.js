/* =========================================================================
   Правовой консультант :: модуль текстовой обработки для полнотекстового поиска
   -------------------------------------------------------------------------
   Используется и сборщиком индекса (tools/build-ft.js), и приложением
   (копируется в data/text.js). Один и тот же алгоритм разбора слов в обоих
   местах — иначе запрос не найдёт то, что проиндексировано.

   Состав:
     tokenize(text)   — слова запроса/текста: строчные буквы, ё -> е,
                        только кириллица, длина >= 3, без служебных слов
     stems(text)      — уникальные основы слов текста
     stemTokens(text) — основы с повторами (частота слова, BM25)
     stem(word)       — основа одного слова
     bucket(word, n)  — номер сегмента индекса для основы
     enc(list)        — упаковка отсортированных номеров статей в строку
     dec(str)         — распаковка
     encPairs(pairs)  — упаковка пар [номер статьи, частота слова]
     decPairs(str)    — распаковка пар

   О стеммере. Классический Snowball для русского языка слишком агрессивен
   для правовых текстов: он отсекает одиночные «в», «н», «л», из-за чего
   «закон» -> «зако», «сроков» -> «сроко», «убийств» -> «убийст», и формы
   одного слова перестают совпадать. Здесь используется консервативный
   стеммер: за один проход снимается ровно одно, самое длинное, окончание из
   списка словоизменительных (падежных, родовых, числовых, глагольных), а
   «опасные» односложные окончания-согласные в список не включены. Это даёт
   устойчивое совпадение словоформ («закон / закона / законов» -> «закон»,
   «статья / статьи / статьями» -> «стат») без разрушения коротких слов.
   ========================================================================= */
(function (root, factory) {
  if (typeof module === "object" && module.exports) module.exports = factory();
  else root.RF_TEXT = factory();
})(typeof self !== "undefined" ? self : this, function () {
  "use strict";

  /* ------------------------------------------------------------ окончания */

  /* Словоизменительные окончания. Порядок в списке не важен: выбирается
     самое длинное подходящее. Одиночные согласные («в», «н», «л», «й»)
     намеренно отсутствуют — они разрушают основу частых слов. */
  var END = [
    /* возвратные частицы */
    "ся", "сь",
    /* деепричастия */
    "вшись", "ившись", "ывшись", "вши", "ивши", "ывши",
    /* прилагательные (причастия сюда не входят: их снимают обычные «-ый/-ий»
       вместе с правилом удвоенной «н», поэтому «ответственный» и
       «ответственность» дают одну основу «ответствен») */
    "ейше", "ейш", "ыми", "ими", "ому", "ему", "ого", "его", "ою", "ею",
    "ых", "их", "ым", "им", "ая", "яя", "ое", "ее", "ые", "ие", "ой", "ей", "ий", "ый",
    "ую", "юю",
    /* существительные */
    "иями", "ями", "ами", "иям", "иях", "ость", "ости", "остью", "ией", "ием",
    "ия", "ии", "ию", "ье", "ья", "ью", "ах", "ях", "ам", "ям", "ом", "ем",
    "ов", "ев",
    /* глаголы */
    "ывать", "ивать", "овать", "евать", "аться", "яться", "иться", "еться",
    "атся", "ятся", "ится", "ется", "ает", "ают", "яет", "яют", "ует", "уют",
    "ать", "ять", "еть", "ить", "ыть", "уть",
    "ала", "яла", "ила", "ыла", "ела", "ало", "яло", "ило", "ыло", "ело",
    "али", "яли", "или", "ыли", "ели",
    "ишь", "ешь", "ите", "йте",
    /* одиночные гласные и мягкий знак */
    "а", "я", "о", "е", "у", "ю", "ы", "и", "ь"
  ];

  var MIN_STEM = 3;   // минимальная длина основы

  /* Окончания, разложенные по последней букве. Подойти слову может только
     окончание с той же последней буквой, поэтому перебирать весь список
     (около 120 строк) на каждое слово незачем. Замер запуска приложения:
     перебор всех окончаний со сравнением через slice() съедал больше
     секунды только на названиях и главах 24 855 статей — это была самая
     дорогая операция при открытии сайта. */
  var END_BY_LAST = (function () {
    var m = {};
    for (var i = 0; i < END.length; i++) {
      var e = END[i], k = e.charAt(e.length - 1);
      (m[k] || (m[k] = [])).push(e);
    }
    return m;
  })();

  /* Основы слов повторяются постоянно: «статья», «право», «суд», «лицо» и
     сотни других встречаются в тысячах названий. Основа слова не зависит от
     контекста, поэтому считаем её один раз. Предел держит память под
     контролем: словарь полного текста всех кодексов больше, чем нужно
     держать целиком. */
  var STEM_CACHE = {}, STEM_CACHE_MAX = 60000, stemCached = 0;

  /* Основа одного слова */
  function stem(w) {
    if (!w || w.length < 4) return w;
    var hit = STEM_CACHE[w];
    if (hit !== undefined) return hit;
    var res = stemRaw(w);
    if (stemCached >= STEM_CACHE_MAX) { STEM_CACHE = {}; stemCached = 0; }
    STEM_CACHE[w] = res;
    stemCached++;
    return res;
  }

  function stemRaw(w) {
    var orig = w;

    /* возвратная частица снимается отдельно */
    if ((w.endsWith("ся") || w.endsWith("сь")) && w.length - 2 >= MIN_STEM) w = w.slice(0, -2);

    /* самое длинное подходящее окончание — из тех, что подходят по последней
       букве; сравниваем через endsWith, без создания подстроки */
    var best = null, cand = END_BY_LAST[w.charAt(w.length - 1)];
    if (cand) {
      for (var i = 0; i < cand.length; i++) {
        var e = cand[i];
        if (w.length - e.length < MIN_STEM) continue;
        if (!w.endsWith(e)) continue;
        if (!best || e.length > best.length) best = e;
      }
    }
    if (best) w = w.slice(0, w.length - best.length);

    /* мягкий знак в конце основы */
    if (w.endsWith("ь") && w.length - 1 >= MIN_STEM) w = w.slice(0, -1);

    /* удвоенная «н» (ответственн- -> ответствен-) */
    if (w.endsWith("нн") && w.length - 1 >= MIN_STEM + 1) w = w.slice(0, -1);

    return w.length >= MIN_STEM ? w : orig;
  }

  /* ------------------------------------------------------------ служебные слова */

  /* Функциональные слова и юридический «шум»: в индекс не попадают */
  var STOP_SRC = (
    "и в во не что он на я с со как а то все она так его но да ты к у же вы за бы по только ее мне " +
    "было вот от меня еще нет о из ему теперь когда даже ну вдруг ли если уже или ни быть был него до " +
    "вас нибудь опять уж вам ведь там потом себя ничего ей может они тут где есть надо ней для мы тебя " +
    "их чем была сам чтоб без будто чего раз тоже себе под будет ж тогда кто этот того потому этого " +
    "какой совсем ним здесь этом один почти мой тем чтобы нее сейчас были куда зачем всех никогда можно " +
    "при наконец два об другой хоть после над больше тот через эти нас про всего них какая много разве " +
    "три эту моя впрочем хорошо свою этой перед иногда лучше чуть том нельзя такой им более всегда " +
    "конечно всю между либо также согласно вроде ввиду всилу всвязи насчет втечение впродолжение " +
    "вцелях вследствие благодаря вопреки наряду помимо кроме сверх вместо данный данного данном " +
    "данным данных иной иного иному иным иных иная иное иные указанный указанного указанном " +
    "указанных указанные соответствующий соответствующих установленный установленного " +
    "установленном установленных установленные установленным предусмотренный предусмотренного " +
    "предусмотренных предусмотренные"
  ).split(/\s+/);

  var STOP = {};
  (function () {
    for (var i = 0; i < STOP_SRC.length; i++) {
      var s = STOP_SRC[i];
      if (!s) continue;
      STOP[s] = 1;
      var st = stem(s);
      if (st.length >= MIN_STEM) STOP[st] = 1;
    }
  })();

  function isStop(w) { return !!STOP[w]; }

  /* ------------------------------------------------------------ токенизация */

  var MIN_LEN = 3;

  function tokenize(text) {
    /* Пустой текст — частый вход: searchable() зовёт stems() шесть раз на
       каждую статью, а у большинства статей заполнены только название и
       глава. Без этой строки на пустом месте всё равно строилась строка,
       снимались «ё» и запускалась регулярка — десятки тысяч раз при
       открытии сайта. */
    if (!text) return [];
    var s = String(text).toLowerCase().replace(/ё/g, "е");
    var m = s.match(/[а-я]+/g);
    if (!m) return [];
    var out = [];
    for (var i = 0; i < m.length; i++) {
      var w = m[i];
      if (w.length < MIN_LEN) continue;
      if (STOP[w]) continue;
      out.push(w);
    }
    return out;
  }

  /* Уникальные основы текста (без повторов) */
  function stems(text) {
    var toks = tokenize(text), seen = {}, out = [];
    for (var i = 0; i < toks.length; i++) {
      var st = stem(toks[i]);
      if (st.length < MIN_LEN) continue;
      if (STOP[st]) continue;
      if (seen[st]) continue;
      seen[st] = 1;
      out.push(st);
    }
    return out;
  }

  /* Основы текста с повторами — для частоты слова в документе (BM25).
     `stems()` отдаёт уникальные основы: этого хватает инвертированному
     индексу «слово -> документы», но не даёт понять, сколько раз слово
     встретилось в статье. Для правовых текстов это сильный сигнал: в статье
     о наркотиках основа «наркотик» повторяется десятки раз, а в случайно
     упомянувшей их норме — один. */
  function stemTokens(text) {
    var toks = tokenize(text), out = [];
    for (var i = 0; i < toks.length; i++) {
      var st = stem(toks[i]);
      if (st.length < MIN_LEN) continue;
      if (STOP[st]) continue;
      out.push(st);
    }
    return out;
  }

  /* ------------------------------------------------------------ сегменты индекса */

  function bucket(word, n) {
    var h = 2166136261 >>> 0;
    for (var i = 0; i < word.length; i++) {
      h ^= word.charCodeAt(i);
      h = Math.imul(h, 16777619) >>> 0;
    }
    return h % n;
  }

  /* ------------------------------------------------------------ упаковка списков */

  var B36 = "0123456789abcdefghijklmnopqrstuvwxyz";

  function toB36(n) {
    if (n === 0) return "0";
    var s = "";
    while (n > 0) { s = B36[n % 36] + s; n = Math.floor(n / 36); }
    return s;
  }
  function fromB36(s) {
    var n = 0;
    for (var i = 0; i < s.length; i++) n = n * 36 + B36.indexOf(s[i]);
    return n;
  }

  /* Список номеров статей -> строка с дельта-кодированием по основанию 36 */
  function enc(list) {
    var out = [], prev = 0;
    for (var i = 0; i < list.length; i++) {
      out.push(toB36(list[i] - prev));
      prev = list[i];
    }
    return out.join(",");
  }

  /* Строка -> массив номеров статей */
  function dec(str) {
    if (!str) return [];
    var parts = str.split(","), out = new Array(parts.length), prev = 0;
    for (var i = 0; i < parts.length; i++) { prev += fromB36(parts[i]); out[i] = prev; }
    return out;
  }

  /* ------------------------------------------------- упаковка с частотой слова */

  /* Список пар [номер статьи, частота слова] -> строка. Номера по-прежнему
     дельта-кодируются по основанию 36, частота дописывается через «~» и
     только когда она больше единицы: у большинства пар она равна единице, и
     «~1» съедало бы по два байта на каждое вхождение (около 2,8 МБ на всём
     индексе). Разделитель «~» не встречается в base36 и в основах слов. */
  function encPairs(pairs) {
    var out = [], prev = 0;
    for (var i = 0; i < pairs.length; i++) {
      var id = pairs[i][0], tf = pairs[i][1];
      out.push(toB36(id - prev) + (tf > 1 ? "~" + toB36(tf) : ""));
      prev = id;
    }
    return out.join(",");
  }

  /* Строка -> массив пар [номер статьи, частота слова] */
  function decPairs(str) {
    if (!str) return [];
    var parts = str.split(","), out = new Array(parts.length), prev = 0;
    for (var i = 0; i < parts.length; i++) {
      var p = parts[i], t = p.indexOf("~"), id;
      if (t === -1) { id = fromB36(p); out[i] = [prev + id, 1]; }
      else { id = fromB36(p.slice(0, t)); out[i] = [prev + id, fromB36(p.slice(t + 1))]; }
      prev += id;
    }
    return out;
  }

  return {
    stem: stem,
    tokenize: tokenize,
    stems: stems,
    stemTokens: stemTokens,
    isStop: isStop,
    bucket: bucket,
    enc: enc,
    dec: dec,
    encPairs: encPairs,
    decPairs: decPairs,
    MIN_LEN: MIN_LEN
  };
});
