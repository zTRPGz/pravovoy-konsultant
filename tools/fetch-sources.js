const UA = "pravovoy-konsultant/0.4 (open legal reference tool; dataset ruslaw-public)";

async function download(base, dir, name) {
  const url = base + encodeURIComponent(name);
  const dest = path.join(dir, name);
  if (fs.existsSync(dest) && fs.statSync(dest).size > 1000) {
    return { name, status: "есть", size: fs.statSync(dest).size };
  }
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error("HTTP " + res.status);
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 1000) throw new Error("слишком маленький ответ: " + buf.length);
  fs.writeFileSync(dest, buf);
  return { name, status: "скачан", size: buf.length };
}

async function batch(label, base, dir, map) {
  const names = Object.keys(map);
  console.log("\n" + label + ": " + names.length + " файлов");
  let total = 0, ok = 0, fail = 0;
  for (const n of names) {
    try {
      const r = await download(base, dir, n);
      total += r.size; ok++;
      console.log("  " + r.status.padEnd(8) + (r.size / 1024).toFixed(0).padStart(7) + " КБ  " + map[n].padEnd(7) + " " + n);
    } catch (e) {
      fail++;
      console.log("  ОШИБКА   " + map[n] + "  " + n + " -> " + e.message);
    }
    await new Promise(r => setTimeout(r, 200)); // вежливая пауза
  }
  console.log("  Итого: " + ok + " из " + names.length + ", объём " + (total / 1048576).toFixed(1) + " МБ");
  return { ok, fail, total };
}

